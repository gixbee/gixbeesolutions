#!/usr/bin/env bash
#
# Gixbee Cloud Agent — environment install script.
#
# Runs after the repository is checked out. It is idempotent and safe to run
# repeatedly: it installs the system services (PostgreSQL, Redis) and the
# Flutter SDK if missing, refreshes every project's dependencies, and
# generates the gitignored local-dev config files (backend/.env,
# lib/firebase_options.dart) with safe placeholder values only.
#
# Long-running services are NOT started here — see .cursor/start.sh.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

FLUTTER_DIR=/opt/flutter
export PATH="$FLUTTER_DIR/bin:$PATH"

echo "== [1/6] System packages (PostgreSQL, Redis) =="
if ! command -v psql >/dev/null 2>&1 || ! command -v redis-server >/dev/null 2>&1; then
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    postgresql postgresql-contrib redis-server \
    curl git unzip xz-utils ca-certificates
fi

echo "== [2/6] Flutter SDK =="
if [ ! -x "$FLUTTER_DIR/bin/flutter" ]; then
  sudo rm -rf "$FLUTTER_DIR"
  sudo git clone --depth 1 -b stable https://github.com/flutter/flutter.git "$FLUTTER_DIR"
fi
# The SDK must be writable by the agent user so `flutter` can manage its cache.
sudo chown -R "$(id -u):$(id -g)" "$FLUTTER_DIR"
git config --global --add safe.directory "$FLUTTER_DIR" || true
sudo ln -sf "$FLUTTER_DIR/bin/flutter" /usr/local/bin/flutter
sudo ln -sf "$FLUTTER_DIR/bin/dart" /usr/local/bin/dart
flutter --version

echo "== [3/6] Backend local env (gitignored placeholder) =="
if [ ! -f backend/.env ]; then
  cat > backend/.env <<'EOF'
# Local development env for the Cloud Agent (generated by .cursor/install.sh).
# Safe placeholder values only — never real secrets.
DATABASE_HOST=localhost
DATABASE_PORT=5432
DATABASE_USER=postgres
DATABASE_PASSWORD=postgres
DATABASE_NAME=gixbee

REDIS_HOST=localhost
REDIS_PORT=6379
REDIS_PASSWORD=

JWT_SECRET=local-dev-jwt-secret-not-for-production-use-only-0123456789
NODE_ENV=development
PORT=3000

# Dev-only: echo the OTP back in the API response so local login works
# without a live SMS provider.
ALLOW_OTP_ECHO=true

# Local super-admin bootstrap credentials (dev only).
ADMIN_USERNAME=admin
ADMIN_PASSWORD=localdevadmin123

LOG_RETENTION_DAYS=30
EOF
  echo "  wrote backend/.env"
else
  echo "  backend/.env already present — leaving it untouched"
fi

echo "== [4/6] Flutter firebase_options.dart (gitignored placeholder) =="
if [ ! -f lib/firebase_options.dart ]; then
  cat > lib/firebase_options.dart <<'EOF'
// GENERATED PLACEHOLDER — created by .cursor/install.sh for the Cloud Agent dev
// environment. This file is .gitignored and is NOT committed.
//
// The real file is produced per-developer with `flutterfire configure` against
// an actual Firebase project. These placeholder values let `flutter analyze`,
// `flutter test`, and compilation succeed without real Firebase credentials.
// Push notifications (FCM) will not deliver with these dummy values, which is
// expected in a headless dev environment — the backend already degrades
// gracefully when Firebase credentials are absent.
//
// ignore_for_file: type=lint
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      return web;
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      case TargetPlatform.macOS:
        return macos;
      case TargetPlatform.windows:
        return windows;
      case TargetPlatform.linux:
        return linux;
      default:
        throw UnsupportedError(
          'DefaultFirebaseOptions are not configured for this platform.',
        );
    }
  }

  static const FirebaseOptions web = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:web:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    authDomain: 'gixbee-dev-placeholder.firebaseapp.com',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
  );

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:android:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:ios:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
    iosBundleId: 'com.gixbee.app',
  );

  static const FirebaseOptions macos = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:ios:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
    iosBundleId: 'com.gixbee.app',
  );

  static const FirebaseOptions windows = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:web:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    authDomain: 'gixbee-dev-placeholder.firebaseapp.com',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
  );

  static const FirebaseOptions linux = FirebaseOptions(
    apiKey: 'placeholder-api-key',
    appId: '1:000000000000:web:0000000000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'gixbee-dev-placeholder',
    authDomain: 'gixbee-dev-placeholder.firebaseapp.com',
    storageBucket: 'gixbee-dev-placeholder.appspot.com',
  );
}
EOF
  echo "  wrote lib/firebase_options.dart"
else
  echo "  lib/firebase_options.dart already present — leaving it untouched"
fi

echo "== [5/6] Node dependencies (backend + super-admin-web) =="
( cd backend && npm ci )
( cd super-admin-web && npm ci )

echo "== [6/6] Flutter dependencies =="
flutter pub get

echo ""
echo "Install complete. Start services with .cursor/start.sh (handled automatically on boot)."
